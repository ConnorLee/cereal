import { test } from 'node:test';
import assert from 'node:assert/strict';
import { userRequest, summarizeCodex, summarizeClaude } from '../lib/agents.mjs';

const AGENTS = '# AGENTS.md instructions for /Users/me/halo\n\n<INSTRUCTIONS>\nPROJECT-SPECIFIC PRODUCT PRINCIPLES\n- Be kind\n</INSTRUCTIONS>';

test('context an agent adds is never taken for what you asked', () => {
  assert.equal(userRequest(AGENTS), null);
  assert.equal(userRequest('# AGENTS.md instructions <INSTRUCTIONS> PROJECT-SPECIFIC'), null);
  assert.equal(userRequest('<environment_context>\n<cwd>/x</cwd>\n</environment_context>'), null);
  assert.equal(userRequest('Caveat: The messages below were generated by the user while running local commands.'), null);
  assert.equal(userRequest('[Request interrupted by user for tool use]'), null);
  assert.equal(userRequest(''), null);
  assert.equal(userRequest(undefined), null);
});

test('the request after pasted files or a referenced conversation is what you asked', () => {
  assert.equal(userRequest(' # Files mentioned by the user:\n\n## Bitmap.png: /Users/me/Bitmap.png\n\n## My request:\nMake the logo bigger\n'), 'Make the logo bigger');
  assert.equal(userRequest('## Referenced ChatGPT conversation:\nlots of text\n## My request for Codex: ship the onboarding'), 'ship the onboarding');
  assert.equal(userRequest('# Files pasted by the user:\n## "notes"\n## My request:\n'), null, 'only context, no request');
  assert.equal(userRequest('Fix the sync bug'), 'Fix the sync bug');
  assert.equal(userRequest('build 41 from claude&#x20; Build &amp; ship &#8212; ok'), 'build 41 from claude  Build & ship — ok');
  assert.equal(userRequest('&lt;not a tag&gt; please'), '<not a tag> please');
});

test('a Codex session is named after the first thing you asked, not its AGENTS.md', () => {
  const meta = { payload: { id: 'abc', cwd: '/x', timestamp: '2026-11-08T10:00:00Z' } };
  const msg = (role, text) => ({ type: 'response_item', timestamp: '2026-11-08T10:00:01Z', payload: { type: 'message', role, content: [{ type: 'input_text', text }] } });
  const s = summarizeCodex(meta, [msg('user', AGENTS), msg('user', '<environment_context>x</environment_context>'), msg('user', 'Add streaks to the habit list')], '/x/rollout-abc.jsonl', new Map());
  assert.equal(s.title, 'Add streaks to the habit list');
  assert.equal(s.task, 'Add streaks to the habit list');
  const none = summarizeCodex(meta, [msg('user', AGENTS)], '/x/rollout-abc.jsonl', new Map());
  assert.match(none.title, /^Codex session 2026-11-08/);
});

test('a Claude Code session skips the local-command caveat', () => {
  const rec = (content) => ({ type: 'user', timestamp: '2026-11-08T10:00:00Z', message: { content } });
  const s = summarizeClaude([rec('Caveat: The messages below were generated by the user while running local commands.'), rec([{ type: 'text', text: 'Tidy the README' }])], '/x/s1.jsonl');
  assert.equal(s.title, 'Tidy the README');
});
